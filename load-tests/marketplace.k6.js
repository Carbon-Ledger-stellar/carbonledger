import http from "k6/http";
import { check, sleep, group } from "k6";
import { Rate, Trend, Counter } from "k6/metrics";
import { uuidv4 } from "https://jslib.k6.io/k6-utils/1.4.0/index.js";

// ── Configuration ─────────────────────────────────────────────────────────────

const BASE_URL = __ENV.BASE_URL || "http://localhost:3001";
const API      = `${BASE_URL}/api/v1`;
const JWT      = __ENV.JWT || "";

// Seed data: must be created by scripts/seed-loadtest.sh before running.
// The seed script writes listing IDs to load-tests/seed-data.json.
// If not present, fall back to well-known test IDs.
let LISTING_IDS = [];
try {
  const seedData = JSON.parse(open("./seed-data.json"));
  LISTING_IDS = seedData.listingIds || [];
} catch (_) {
  // Fallback: generated by seed-loadtest.sh convention
  LISTING_IDS = Array.from({ length: 20 }, (_, i) =>
    `listing-loadtest-${String(i + 1).padStart(4, "0")}`
  );
}

// ── Custom metrics ────────────────────────────────────────────────────────────

const browseErrors          = new Rate("browse_errors");
const purchaseErrors        = new Rate("purchase_errors");
const retirementErrors      = new Rate("retirement_errors");

const browseDuration        = new Trend("browse_duration",      true);
const purchaseDuration      = new Trend("purchase_duration",    true);
const retirementDuration    = new Trend("retirement_duration",  true);

const purchaseCount         = new Counter("purchase_total");
const retirementCount       = new Counter("retirement_total");

// ── Test options ──────────────────────────────────────────────────────────────

