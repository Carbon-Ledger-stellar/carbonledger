// ── Helpers ───────────────────────────────────────────────────────────────────

function randomItem(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function authHeaders() {
  const headers = { "Content-Type": "application/json" };
  if (JWT) headers["Authorization"] = `Bearer ${JWT}`;
  return headers;
}

/** Generate a wallet-style public key for test buyers. */
function buyerKey(vu) {
  return `GBLOADTEST${String(vu).padStart(46, "0").slice(0, 46)}`;
}

// ── Setup: verify reachability and warm up ────────────────────────────────────

export function setup() {
  const health = http.get(`${BASE_URL}/health`);
  if (health.status !== 200) {
    throw new Error(
      `API health check failed: status=${health.status} url=${BASE_URL}/health\n` +
      `Ensure the staging server is running and run scripts/seed-loadtest.sh first.`
    );
  }
  console.log(`✓ API reachable at ${BASE_URL}`);
  console.log(`✓ ${LISTING_IDS.length} listing IDs loaded`);

  if (!JWT) {
    console.warn(
      "⚠  No JWT set — purchase and retirement requests will receive 401. " +
      "Set -e JWT=<token> for full scenario coverage."
    );
  }

  return { listingIds: LISTING_IDS };
}

// ── Scenario 1: Marketplace Browse ────────────────────────────────────────────
// Tests the paginated GET /marketplace/listings endpoint.
// Updated to use ?page=N&pageSize=20 (current API contract).

function scenarioBrowse() {
  const methodologies = ["VCS", "Gold Standard", "ACR", "CAR", "Plan Vivo"];
  const vintages      = ["2020", "2021", "2022", "2023", "2024"];
  const page          = Math.ceil(Math.random() * 5); // pages 1–5

  group("marketplace_browse", () => {
    // ── GET /marketplace/listings (paginated) ─────────────────────────────────
    const params = new URLSearchParams({
      page:        String(page),
      pageSize:    "20",
      methodology: randomItem(methodologies),
      vintage:     randomItem(vintages),
    });

    const res = http.get(`${API}/marketplace/listings?${params}`, {
      tags: { name: "GET /listings" },
    });

    browseDuration.add(res.timings.duration);

    const ok = check(res, {
      "browse: status 200":        (r) => r.status === 200,
      "browse: has data array":    (r) => {
        try {
          const body = r.json();
          return Array.isArray(body.data || body) || typeof body === "object";
        } catch { return false; }
      },
      "browse: response < 2000ms": (r) => r.timings.duration < 2000,
    });

    browseErrors.add(!ok || res.status >= 500);

    // 40% of browsers also fetch a single listing detail
    if (Math.random() < 0.4 && LISTING_IDS.length > 0) {
      const listingId = randomItem(LISTING_IDS);
      const detail = http.get(`${API}/marketplace/listings/${listingId}`, {
        tags: { name: "GET /listing/:id" },
      });
      check(detail, {
        "listing detail: 200 or 404": (r) => r.status === 200 || r.status === 404,
      });
    }
  });

  sleep(0.5 + Math.random());
}

// ── Scenario 2: Purchase Stress ────────────────────────────────────────────────
// Each VU completes a full flow: browse listing → post purchase → check receipt.

function scenarioPurchase() {
  const listingId = randomItem(LISTING_IDS);

  group("purchase_flow", () => {
    // Step 1: browse a listing to confirm availability
    const browse = http.get(`${API}/marketplace/listings/${listingId}`, {
      tags: { name: "GET /listing (pre-purchase)" },
    });

    // 404 means seed data is exhausted — treat as non-error
    if (browse.status === 404) {
      return;
    }

    check(browse, { "pre-purchase browse: 200": (r) => r.status === 200 });

    // Step 2: post the purchase
    const payload = JSON.stringify({
      listingId,
      amount:         1,
      buyerPublicKey: buyerKey(__VU),
    });

    const purchase = http.post(`${API}/marketplace/purchase`, payload, {
      headers: authHeaders(),
      tags:    { name: "POST /purchase" },
    });

    purchaseDuration.add(purchase.timings.duration);

    const ok = check(purchase, {
      "purchase: 201 created or 400 conflict": (r) =>
        r.status === 201 || r.status === 400 || r.status === 401,
      "purchase: response < 2000ms": (r) => r.timings.duration < 2000,
    });

    // Only count 5xx as purchase errors
    purchaseErrors.add(purchase.status >= 500);

    if (ok && purchase.status === 201) {
      purchaseCount.add(1);

      // Step 3: verify receipt (optional — non-blocking)
      try {
        const txHash = purchase.json("txHash");
        if (txHash) {
          http.get(`${API}/marketplace/receipt/${txHash}`, {
            tags: { name: "GET /receipt" },
          });
        }
      } catch (_) { /* JSON parse errors are non-fatal here */ }
    }
  });

  sleep(1 + Math.random() * 2);
}

// ── Scenario 3: Bulk Retirement Spike ─────────────────────────────────────────
// Simulates 10 large corporate buyers all submitting 10-item bulk retirements
// simultaneously — the year-end ESG reporting rush.

function scenarioBulkRetirement() {
  group("bulk_retirement", () => {
    // Build a 10-item retirement batch
    const items = Array.from({ length: 10 }, (_, i) => ({
      batchId:     randomItem(LISTING_IDS),
      amount:      1,
      beneficiary: `Corp-VU${__VU}-Item${i}`,
      reason:      `Year-end ESG offset ${new Date().getFullYear()} — item ${i + 1}/10`,
    }));

    const payload = JSON.stringify({
      retirements: items,
      corporateName: `LoadTestCorp-VU${__VU}`,
      reportingPeriod: `${new Date().getFullYear()}-FY`,
    });

    const res = http.post(`${API}/retirements/bulk`, payload, {
      headers: authHeaders(),
      tags:    { name: "POST /retirements/bulk" },
    });

    retirementDuration.add(res.timings.duration);

    const ok = check(res, {
      "bulk retire: 201 or 400 or 401":  (r) =>
        r.status === 201 || r.status === 400 || r.status === 401,
      "bulk retire: response < 2000ms":  (r) => r.timings.duration < 2000,
    });

    // 5xx = error; 400/401 without JWT = expected in load env
    retirementErrors.add(res.status >= 500);

    if (res.status === 201) {
      retirementCount.add(1);
    }
  });

  sleep(2 + Math.random() * 3);
}

// ── Main entry point ─────────────────────────────────────────────────────────
// Route each VU to its scenario based on exec.scenario.name.

import exec from "k6/execution";

export default function (data) {
  const scenario = exec.scenario.name;

  if (scenario === "marketplace_browse") {
    scenarioBrowse();
  } else if (scenario === "purchase_stress") {
    scenarioPurchase();
  } else if (scenario === "bulk_retirement_spike") {
    scenarioBulkRetirement();
  } else {
    // Fallback: run browse
    scenarioBrowse();
  }
}

